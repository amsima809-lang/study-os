type Translate = (key: string, vars?: Record<string, string | number>) => string;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
};

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "studyos.lang";

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "th" || v === "en") return v;
  } catch {
    // localStorage may be blocked (private mode) — fall back to default.
  }
  return "th";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // ignore write failures
    }
  }, [lang]);

  const value = useMemo<I18nValue>(() => {
    const t: Translate = (key, vars) => {
      let s = STRINGS[lang][key] ?? STRINGS.th[key] ?? key;
      if (vars) {
        for (const [k, val] of Object.entries(vars)) {
          s = s.replace(`{${k}}`, String(val));
        }
      }
      return s;
    };
    return { lang, setLang: setLangState, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useT must be used inside <LanguageProvider>");
  return ctx;
}

/** The TH / EN toggle button. */
export function LanguageToggle() {
  const { lang, setLang, t } = useT();

  function btnStyle(active: boolean): React.CSSProperties {
    return active
      ? { backgroundColor: "var(--bg-surface-hover)", color: "var(--text-primary)", border: "1px solid var(--border)" }
      : { backgroundColor: "transparent", color: "var(--text-tertiary)", border: "1px solid var(--border-light)" };
  }

  return (
    <div className="inline-flex gap-1" role="group" aria-label="language">
      <button
        className="px-3 py-1 text-sm font-medium rounded-full transition-colors"
        style={btnStyle(lang === "th")}
        onClick={() => setLang("th")}
      >
        {t("lang.th")}
      </button>
      <button
        className="px-3 py-1 text-sm font-medium rounded-full transition-colors"
        style={btnStyle(lang === "en")}
        onClick={() => setLang("en")}
      >
        {t("lang.en")}
      </button>
    </div>
  );
}
