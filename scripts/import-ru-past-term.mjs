// Keep a PAST term's ม.ร.30 as reference: every course it offered, with its class days and
// times, rooms, lecturers and exam date, in `term_offerings` under that term's id ("S/68").
// Nothing else changes: no timetable, no exams, no credits. The trail planner shows it as
// "when this ran last time" for a term whose own list is not out yet (the summer terms).
//
// Usage (from the repo root; the PDFs are NOT kept in the repo):
//   node scripts/import-ru-past-term.mjs <NNN_name.sql> <mr30.pdf> [<mr30.pdf> ...]
//   node scripts/import-ru-past-term.mjs 039_past_summers.sql ~/Downloads/20250113_S67.pdf ~/Downloads/20260106_S68.pdf
//
// The PDFs are the registrar's (สวป.), at http://www.regis.ru.ac.th/document/6_regis_examSV/MorLor30/.
// Each names its own term in its title. A PDF is refused unless the number of courses read
// equals the total printed on its last page, and every course has a name and a class line.
// A summer ม.ร.30 prints its exam dates in the same table, so there is no separate exam list.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { readMr30, readOffered, offeringRow, q } from "./lib/mr30.mjs";

const [outName, ...pdfs] = process.argv.slice(2);
if (!/^\d{3}_[a-z0-9_]+\.sql$/.test(outName ?? "") || pdfs.length === 0) {
  console.error("usage: node scripts/import-ru-past-term.mjs <NNN_name.sql> <mr30.pdf> [<mr30.pdf> ...]");
  process.exit(1);
}

const terms = [], problems = [];
for (const path of pdfs) {
  const { term } = await readOffered(path); // the term, from the title
  const r = await readMr30(path);
  const file = basename(path);
  if (!term) { problems.push(`${file}: no term found in the title`); continue; }
  if (terms.some((t) => t.term === term)) { problems.push(`${file}: term ${term} was given twice`); continue; }
  if (r.printedTotal !== r.courses.size) problems.push(`${file} (${term}): prints a total of ${r.printedTotal} courses but ${r.courses.size} were read`);
  for (const c of r.courses.values()) {
    if (c.sessions.length === 0) problems.push(`${file}: ${c.code} has no class line`);
    if (!c.name.join("").replace(/\([^)]*\)/, "").trim()) problems.push(`${file}: ${c.code} has no name`);
  }
  const timed = [...r.courses.values()].filter((c) => c.sessions.some((s) => s.weekday)).length;
  const dated = [...r.courses.values()].filter((c) => c.exam?.date).length;
  terms.push({ term, r, file, timed, dated, sha: createHash("sha256").update(readFileSync(path)).digest("hex") });
  console.log(`${file.padEnd(24)} ${term}  read ${r.courses.size}  printed ${r.printedTotal}  with class days ${timed}  with an exam date ${dated}`);
}
if (problems.length) { console.error(`Not written. ${problems.length} problem(s):\n  ` + problems.slice(0, 30).join("\n  ")); process.exit(1); }

const chunks = (list, size) => { const out = []; for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size)); return out; };
const sql = `-- Migration ${outName.slice(0, 3)}: past terms kept as reference, from the registrar's ม.ร.30.
-- GENERATED by scripts/import-ru-past-term.mjs. Do not edit by hand: fix the script and run it again.
--
-- Sources (Ramkhamhaeng University, สวป., http://www.regis.ru.ac.th/document/6_regis_examSV/MorLor30/):
${terms.map((t) => `--   ${t.term.padEnd(5)} ${String(t.r.courses.size).padStart(4)} courses (= printed total), ${t.timed} with class days, ${t.dated} with an exam date  ${t.file}  sha256 ${t.sha}`).join("\n")}
--
-- These terms are OVER. Their rows are what ran then: class days and times, rooms, lecturers,
-- exam dates. The app shows them only as "last time it ran" beside a future term whose own
-- list is not published yet, and never as that term's timetable. Summer day groups: MWF =
-- Monday, Wednesday, Friday; TTS = Tuesday, Thursday, Saturday (scripts/lib/mr30.mjs).

${terms.map((t) => `DELETE FROM term_offerings WHERE term_id = ${q(t.term)};
${chunks([...t.r.courses.values()].map((c) => offeringRow(t.term, c, t.r.depts)), 200).map((part) => `INSERT INTO term_offerings (term_id, course_code, credits, name_en, old_code, dept, dept_name, notes, sessions, teachers, exam_date, exam_slot, exam_note, source_page) VALUES\n${part.join(",\n")};`).join("\n")}`).join("\n\n")}
`;
writeFileSync(`server/migrations/${outName}`, sql);
console.log(`server/migrations/${outName}: ${terms.map((t) => t.term).join(", ")} (${(sql.length / 1024).toFixed(0)} KB)`);
