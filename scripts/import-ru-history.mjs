// Build a migration recording WHICH TERMS each course has been offered in, from past editions
// of the registrar's ม.ร.30 (http://www.regis.ru.ac.th/document/6_regis_examSV/MorLor30/).
// The long-term planner uses it to place a course in a term it has actually run in.
//
// Usage (from the repo root; the PDFs are NOT kept in the repo):
//   node scripts/import-ru-history.mjs <NNN_name.sql> <mr30.pdf> [<mr30.pdf> ...]
//
// Each PDF names its own term in its title and prints its own total on the last page. A PDF
// is refused unless the number of courses read equals that total. Nothing is typed by hand.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { readOffered } from "./lib/mr30.mjs";

const [outName, ...pdfs] = process.argv.slice(2);
if (!/^\d{3}_[a-z0-9_]+\.sql$/.test(outName ?? "") || pdfs.length === 0) {
  console.error("usage: node scripts/import-ru-history.mjs <NNN_name.sql> <mr30.pdf> [<mr30.pdf> ...]");
  process.exit(1);
}
const order = (t) => +t.slice(2) * 10 + ({ 1: 1, 2: 2, S: 3 })[t[0]]; // 1/67 < 2/67 < S/67 < 1/68
const terms = [], problems = [];
for (const path of pdfs) {
  const r = await readOffered(path);
  if (!r.term) problems.push(`${basename(path)}: no term found in the title`);
  else if (r.printedTotal === null) problems.push(`${basename(path)} (${r.term}): no total printed on the last page`);
  else if (r.printedTotal !== r.courses.size) problems.push(`${basename(path)} (${r.term}): prints a total of ${r.printedTotal} courses but ${r.courses.size} were read`);
  else if (terms.some((t) => t.term === r.term)) problems.push(`${basename(path)}: term ${r.term} was given twice`);
  else terms.push({ ...r, file: basename(path), sha: createHash("sha256").update(readFileSync(path)).digest("hex") });
  console.log(`${basename(path).padEnd(26)} ${r.term ?? "?"}  read ${r.courses.size}  printed total ${r.printedTotal}`);
}
if (problems.length) { console.error(`Not written. ${problems.length} problem(s):\n  ` + problems.join("\n  ")); process.exit(1); }
terms.sort((a, b) => order(a.term) - order(b.term));

const rows = terms.flatMap((t) => [...t.courses.keys()].map((code) => `('${t.term}','${code}')`));
const chunks = []; for (let i = 0; i < rows.length; i += 400) chunks.push(rows.slice(i, i + 400));
const sql = `-- Migration ${outName.slice(0, 3)}: which terms each course has been offered in.
-- GENERATED by scripts/import-ru-history.mjs. Do not edit by hand: fix the script and run it again.
--
-- Source: past editions of the registrar's ม.ร.30 (Ramkhamhaeng University, สวป.). For each, the
-- number of courses read equals the total printed on its last page.
${terms.map((t) => `--   ${t.term}  ${String(t.courses.size).padStart(5)} courses  ${t.file}  sha256 ${t.sha}`).join("\n")}
--
-- Used by the long-term planner: a course is placed in a first term, second term or summer
-- only if it has run in one before. It says what HAS happened; the university may change it.

CREATE TABLE IF NOT EXISTS course_offering_history (
  term_id     TEXT NOT NULL,   -- "1/67", "2/67", "S/67" (summer) …
  course_code TEXT NOT NULL,
  PRIMARY KEY (term_id, course_code)
) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS idx_offering_history_course ON course_offering_history(course_code);

DELETE FROM course_offering_history WHERE term_id IN (${terms.map((t) => `'${t.term}'`).join(", ")});
${chunks.map((c) => `INSERT INTO course_offering_history (term_id, course_code) VALUES ${c.join(",")};`).join("\n")}
`;
writeFileSync(`server/migrations/${outName}`, sql);
console.log(`server/migrations/${outName}: ${terms.length} terms (${terms.map((t) => t.term).join(", ")}), ${rows.length} rows, ${(sql.length / 1024).toFixed(0)} KB`);
